// The airline flying a callsign: three letters then a number (UAL2652). A private
// registration (N828WW) or an unknown prefix gives null.
export function airlineOf(callsign: string | null): Airline | null {
  const prefix = callsign?.match(/^([A-Z]{3})\d/)?.[1];
  return prefix ? (AIRLINES[prefix] ?? null) : null;
}

// "Boeing 737-900" for B739; the code itself when it's not on the list.
export function typeName(code: string | null) {
  return code ? (TYPES[code] ?? code) : null;
}
